"""Generate the Airlite CML constraint model from the Airlite template + configurator.

Usage: python build_airlite_cml.py AIRLITE_TEMPLATE.xlsx AIRLITE_CONFIGURATOR.xlsm OUT.cml SUFFIX

Uses only constructs proven in the ECO model (see 01-skill/.../references/cml_syntax_rules.md):
string picklists with @(defaultValue), decimal(n) variables, constraint(table(...)),
constraint(cond -> ...), message(cond, "text", "Warning"|"Error"|"Info").
Av and Aa are pre-computed tables (no decimal arithmetic -> no tree-node search limit).
"""
import sys, warnings
import openpyxl

warnings.filterwarnings("ignore")
tpl_path, cfg_path, out_path, SFX = sys.argv[1:5]
P = "AIR"
A = lambda name: f"{P}_{name}{SFX}"

# ---- picklist values and defaults from the template ----------------------------------
tpl = openpyxl.load_workbook(tpl_path, data_only=True)
values = {}
for r in tpl["AttributePicklistValue"].iter_rows(min_row=3, values_only=True):
    if r[0] and r[1] is not None:
        values.setdefault(r[0], []).append(str(r[1]))
attr_pl, attr_type = {}, {}
for r in tpl["AttributeDefinition"].iter_rows(min_row=3, values_only=True):
    if r[10]:
        attr_pl[r[10]] = r[9]
        attr_type[r[10]] = r[5]
defaults = {r[2]: r[3] for r in tpl["Product and Attributes"].iter_rows(min_row=3, values_only=True) if r[2] and r[3]}
product_code = next(r[7] for r in tpl["Product"].iter_rows(min_row=6, values_only=True) if r[4])

# ---- Aa tables from the configurator (Aerodynamik sheet) -----------------------------
aero = openpyxl.load_workbook(cfg_path, data_only=True)["Aerodynamik"]
blocks = {"A0": 14, "A2": 27, "E1": 40, "E2": 53}       # header row of each 4x9 table
LENGTHS = [int(aero.cell(14, c).value) for c in range(2, 11)]
GRID_W = [500, 1000, 1500, 2000]
grid = {}
for inst, hr in blocks.items():
    for i, w in enumerate(GRID_W):
        assert int(aero.cell(hr + 1 + i, 1).value) == w
        for j, L in enumerate(LENGTHS):
            grid[(inst, w, L)] = float(aero.cell(hr + 1 + i, 2 + j).value)


def xround(x, n=2):  # Excel ROUND (half away from zero)
    from decimal import Decimal, ROUND_HALF_UP
    return float(Decimal(repr(x)).quantize(Decimal(1).scaleb(-n), rounding=ROUND_HALF_UP))


def aa(inst, W, L):
    """Aerodynamik!B78 = ROUND(TREND(C75:C76, B75:B76, W), 2)."""
    wmin = 500 if W <= 999 else 1000 if W <= 1499 else 1500 if W <= 1999 else 2000
    wmax = 500 if W == 500 else 1000 if W <= 1000 else 1500 if W <= 1500 else 2000
    y1, y2 = grid[(inst, wmin, L)], grid[(inst, wmax, L)]
    if wmin == wmax:
        return xround(y1)
    return xround(y1 + (y2 - y1) * (W - wmin) / (wmax - wmin))


widths = [int(v) for v in values[f"{P} Width{SFX}"]]
lengths = [int(v) for v in values[f"{P} Length{SFX}"]]
assert lengths == LENGTHS, (lengths, LENGTHS)

# ---- helpers --------------------------------------------------------------------------
out = []
w = out.append


def any_of(attr, vals):
    return " || ".join(f'{attr} == "{v}"' for v in vals)


def section(n, title):
    w("")
    w("    // " + "═" * 70)
    w(f"    //  {n}.  {title}")
    w("    // " + "═" * 70)


def rows(entries, per_line=4):
    lines = []
    for i in range(0, len(entries), per_line):
        lines.append("        " + ", ".join(entries[i:i + per_line]))
    return ",\n".join(lines)


controls = values[f"{P} Controls{SFX}"]
PNEU = [c for c in controls if c.startswith("P")]
ELEC = [c for c in controls if c.startswith("M")]
TWO = [c for c in controls if c[1] == "2"]
V24 = [c for c in ("M1B24", "M2B24") if c in controls]
louvres = values[f"{P} Louvre{SFX}"]

# ---- header + declarations ----------------------------------------------------------
w("// " + "═" * 75)
w(f"//  Airlite {product_code} – Constraint Model (Revenue Cloud Advanced)")
w("//  Source: Airlite Tech. Configurator v1.54 (Input rules AH/AJ, Aerodynamik, Flanges)")
w(f"//  Generated by build_airlite_cml.py – attribute names carry suffix '{SFX}'")
w("//  Syntax limited to constructs proven in the ECO model; see cml_syntax_rules.md.")
w("// " + "═" * 75)
w("")
w("type LineItem;")
w("")
w(f"type Airlite{product_code} : LineItem {{")
w("")
w("    // " + "─" * 70)
w("    //  INPUT ATTRIBUTES – picklists")
w("    // " + "─" * 70)
for code, dt in attr_type.items():
    if dt != "Picklist":
        continue
    vals = values[attr_pl[code]]
    if code in defaults:
        w(f'    @(defaultValue = "{defaults[code]}")')
    w(f"    string {code} = [{', '.join(chr(34) + v + chr(34) for v in vals)}];")
    w("")
w("    // " + "─" * 70)
w("    //  INPUT ATTRIBUTES – free number / text (checked with message(), not hard constraints)")
w("    // " + "─" * 70)
OUTPUT_CODES = {A(x) for x in ["CylinderType", "CO2Bottle", "StandbyReservoir", "ElectricDrive", "WindSuctionLoad",
                                "GeomAreaAv", "AeroAreaAa", "UValue", "LouvreWeight", "TotalWeight",
                                "MaxSLCylinder", "MaxSLMotor"]}
for code, dt in attr_type.items():
    if dt == "Picklist" or code in OUTPUT_CODES:
        continue
    w(f"    {'string' if dt == 'Text' else 'decimal(1)' if 'Pressure' in code else 'decimal(0)'} {code};")
w("")
w("    // " + "─" * 70)
w("    //  PROXY VARIABLES – width / length in mm (not PCM attributes)")
w("    // " + "─" * 70)
w(f"    decimal(0) {A('Width_mm')};")
w(f"    decimal(0) {A('Length_mm')};")
w("")
w("    // " + "─" * 70)
w("    //  OUTPUT ATTRIBUTES – read-only, set by tables below (others via Apex / factory)")
w("    // " + "─" * 70)
for code in sorted(OUTPUT_CODES, key=list(attr_type).index):
    w(f"    {'string' if attr_type[code] == 'Text' else 'decimal(2)'} {code};")
for code in sorted(OUTPUT_CODES, key=list(attr_type).index):
    w(f'    rule(true, "disable", "attribute", "{code}");')

# ---- 1. code -> mm ---------------------------------------------------------------------
section(1, "WIDTH / LENGTH CODE → MM  (table constraints)")
w(f"    constraint(table({A('Width')}, {A('Width_mm')},")
w(rows([f'{{"{x}", {x}}}' for x in widths], 6) + "),")
w('        "Width code to mm");')
w("")
w(f"    constraint(table({A('Length')}, {A('Length_mm')},")
w(rows([f'{{"{x}", {x}}}' for x in lengths], 6) + "),")
w('        "Length code to mm");')

# ---- 2. Av -------------------------------------------------------------------------------
section(2, f"GEOMETRIC AREA Av = W × L / 10^6  ({len(widths) * len(lengths)} pre-computed entries)")
w(f"    constraint(table({A('Width')}, {A('Length')}, {A('GeomAreaAv')},")
w(rows([f'{{"{W}", "{L}", {xround(W * L / 1e6):.2f}}}' for W in widths for L in lengths], 4) + "),")
w('        "Geometric area Av");')

# ---- 3. Aa -------------------------------------------------------------------------------
section(3, "AERODYNAMIC AREA Aa per installation type (Aerodynamik sheet, width interpolation)")
for inst in blocks:
    w(f'    constraint({A("InstallationType")} == "{inst}" ->')
    w(f"        table({A('Width')}, {A('Length')}, {A('AeroAreaAa')},")
    w(rows([f'{{"{W}", "{L}", {aa(inst, W, L):.2f}}}' for W in widths for L in lengths], 4) + "),")
    w(f'        "Aerodynamic area Aa – installation {inst}");')
    w("")

# ---- 4. certification rules (Input columns AH = 1E, AJ = 1S) -----------------------------
V, C_, TR = A("Version"), A("Controls"), A("ThermalRelease")
section(4, "CERTIFICATION RULES – Input sheet columns AH (1E) / AJ (1S)")
w(f"    constraint(({any_of(C_, TWO)}) -> {A('Width_mm')} >= 700,")
w('               "Min. width with 2 actuators is 700 mm.");')
w("")
w(f"    constraint(({any_of(C_, ELEC)}) -> {TR} == \"FX\",")
w('               "Electric controls only in combination with FX.");')
w("")
w(f"    constraint({V} == \"1E\" && ({any_of(C_, PNEU)}) -> {TR} != \"FFX\",")
w('               "1E: pneumatic controls not with FFX.");')
w("")
w(f"    constraint({A('Louvre')} == \"GL24\" -> ({A('InstallationType')} == \"A0\" || {A('InstallationType')} == \"A2\"),")
w('               "GL24 is invalid by installation into wall (E1, E2).");')
w("")
w(f"    constraint({A('BaseDesign')} == \"E\" -> {A('FlangeType')} == \"N5\",")
w('               "Base design E is only possible with a N5 flange.");')
w("")
w(f"    constraint(({A('InstallationType')} == \"A0\" || {A('InstallationType')} == \"A2\") -> {A('WindBaffle')} == \"WM\",")
w('               "Flat roof installation (A0, A2) requires the movable wind baffle WM.");')
w("")
w(f"    constraint(({A('InstallationType')} == \"E1\" || {A('InstallationType')} == \"E2\") -> {A('WindBaffle')} == \"W0\",")
w('               "No movable wind baffle required for wall installation (E1, E2).");')
w("")
w(f"    constraint({V} == \"1E\" && {A('Louvre')} != \"GL24\" -> {A('Delivery')} == \"CA\",")
w('               "1E: break down (BD) only in combination with glass louvres GL24.");')
w("")
w(f"    constraint(({any_of(C_, V24)}) -> {A('AmbientTemp')} == \"T(-25)\",")
w('               "24 V actuators: ambient air temperature class T(-25).");')
w("")
w(f"    constraint(({any_of(C_, [c for c in controls if c not in V24])}) -> {A('AmbientTemp')} == \"T(-15)\",")
w('               "Ambient air temperature class T(-15) for the chosen actuator.");')

# ---- 5. numeric checks as messages ----------------------------------------------------
MA, PD, PS = A("MountingAngle"), A("PressureDaily"), A("PressureSmoke")
section(5, "NUMERIC CHECKS – message() so free numbers never trigger the search limit")
w(f"    message({MA} < 0 || {MA} > 90,")
w('            "Mounting angle must be between 0 and 90°.", "Error");')
w("")
w(f"    message({V} == \"1E\" && ({A('InstallationType')} == \"E1\" || {A('InstallationType')} == \"E2\") && {MA} != 90,")
w('            "1E: installation in wall only with mounting angle 90°.", "Error");')
w("")
w(f"    message({V} == \"1E\" && {A('Louvre')} == \"GL24\" && {MA} > 20,")
w('            "1E: GL24 max. mounting angle 20°.", "Error");')
w("")
w(f"    message(({any_of(C_, PNEU)}) && ({PD} < 6 || {PD} > 30 || {PS} < 6 || {PS} > 30),")
w('            "Pressure out of the valid pressure range (min. 6 bar, max. cylinder pressure ≤ 30 bar).", "Error");')
w("")
w(f"    message(({TR} == \"FFX\" || {TR} == \"FF68\" || {TR} == \"FF93\") && ({PD} != {PS} || {PD} > 12),")
w('            "Failsafe: day-to-day pressure must equal smoke pressure, max. 12 bar.", "Error");')
w("")
w(f"    message({A('Coating')} != \"X\" && {A('RALColour')} == \"\",")
w('            "Insert RAL colour for the selected coating.", "Warning");')
w("")
w(f"    message({A('Coating')} != \"X\" && {A('Coating')} != \"W\" && {A('Width_mm')} > 1900 && {A('Length_mm')} > 1900,")
w('            "Coated units: the shorter side must not be larger than 1900 mm.", "Warning");')

# ---- 6. flange limits ---------------------------------------------------------------------
FW, FL, WM, LM, FT, BD = A("FlangeWidth"), A("FlangeLength"), A("Width_mm"), A("Length_mm"), A("FlangeType"), A("BaseDesign")
flanges = values[f"{P} Flange Type{SFX}"]
fam = lambda pre: [f for f in flanges if f.startswith(pre)]
section(6, "FLANGE DIMENSION LIMITS (Flanges sheet) – warnings, only once both flange sizes are entered")
w(f"    message({FW} <= 0 || {FL} <= 0,")
w('            "Enter flange width and length in mm (configurator default for N5: width + 250 / length + 250).", "Info");')
w("")
w(f"    message({FW} > 0 && {FL} > 0 && ({any_of(FT, fam('N1'))}) && ({FW} < {WM} + 150 || {FW} > {WM} + 200 || {FL} < {LM} + 150 || {FL} > {LM} + 500),")
w('            "N1 flange: width +150…+200 mm, length +150…+500 mm. Check with the GPTS.", "Warning");')
w("")
w(f"    message({FW} > 0 && {FL} > 0 && ({any_of(FT, ['N2', 'N3', 'N4', 'N7', 'NS'])}) && ({FW} < {WM} + 150 || {FL} < {LM} + 150),")
w('            "Flange must be at least +150 mm on width and length. Check with the GPTS.", "Warning");')
w("")
w(f"    message({FW} > 0 && {FL} > 0 && {FT} == \"N5\" && {BD} != \"E\" && ({FW} < {WM} + 150 || {FW} > {WM} + 500 || {FL} < {LM} + 150 || {FL} > {LM} + 500),")
w('            "N5 flange: +150…+500 mm on width and length. Check with the GPTS.", "Warning");')
w("")
w(f"    message({FW} > 0 && {FL} > 0 && {FT} == \"N5\" && {BD} == \"E\" && ({FW} != {WM} + 250 || {FL} != {LM} + 250),")
w('            "N5 flange with base E: flange must be exactly +250 mm. Check with the GPTS.", "Warning");')
w("")
for fam_pre, wS, lS in (("N6", 300, 355), ("N8", 350, 380)):
    w(f"    message({FW} > 0 && {FL} > 0 && ({any_of(FT, fam(fam_pre))}) && {BD} == \"S\" && ({FW} < {WM} + {wS} || {FL} < {LM} + {lS}),")
    w(f'            "{fam_pre} flange with base S: min. width +{wS} mm, length +{lS} mm. Check with the GPTS.", "Warning");')
    w("")
    w(f"    message({FW} > 0 && {FL} > 0 && ({any_of(FT, fam(fam_pre))}) && {BD} == \"H\" && ({FW} < {WM} + 250 || {FL} < {LM} + 330),")
    w(f'            "{fam_pre} flange with base H: min. width +250 mm, length +330 mm. Check with the GPTS.", "Warning");')
    w("")
    w(f"    message({FW} > 0 && {FL} > 0 && ({any_of(FT, fam(fam_pre))}) && {BD} == \"E\" && ({FW} < {WM} + 300 || {FL} < {LM} + 300),")
    w(f'            "{fam_pre} flange with base E: min. +300 mm. Check with the GPTS.", "Warning");')
    w("")

# ---- 7. checks that need the factory calculation sheets -------------------------------
section(7, "LOAD CHECKS – need the configurator's calculation sheets (Apex / factory)")
w(f"    message(({any_of(C_, PNEU)}) && {TR} != \"FX\" && {TR} != \"FFX\",")
w('            "Pneumatic with thermal release: CO2 bottle (min. 20 g) and cylinder size to be confirmed from the configurator.", "Info");')
w("")
w(f"    message({A('SnowLoad')} > 0,")
w('            "Snow load: max. SL of cylinder / motor to be checked in the Airlite configurator (SL sheets).", "Info");')
w("")
w(f"    message({V} == \"1E\" && {A('WindLoad')} > 0,")
w('            "1E: wind suction load to be checked in the Airlite configurator (Windload sheet).", "Info");')
w("}")

open(out_path, "w", encoding="utf-8").write("\n".join(out) + "\n")
print(f"{out_path}: {len(out)} lines, Av entries {len(widths) * len(lengths)}, "
      f"Aa entries {len(widths) * len(lengths) * len(blocks)}")
